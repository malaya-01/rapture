#!/usr/bin/env node
/**
 * Generates src/data/books-registry.ts from seed/books.json + per-book book.json
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { getBooksRegistry } from "./book-config.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..", "..");
const outDir = join(root, "src", "data");

function esc(s) {
  return String(s ?? "").replace(/\\/g, "\\\\").replace(/`/g, "\\`");
}

const { libraryName, books } = getBooksRegistry();

const enriched = books.map((book) => {
  const bookJsonPath = join(root, book.seedDir, "book.json");
  const meta = existsSync(bookJsonPath)
    ? JSON.parse(readFileSync(bookJsonPath, "utf8"))
    : {};
  return {
    ...book,
    totalChapters: meta.totalChapters ?? 0,
    totalVolumes: meta.totalVolumes ?? 0,
  };
});

const ts = `/** AUTO-GENERATED by seed/scripts/sync-books-registry.mjs — edit seed/books.json and per-book book.json */
import type { Book } from "@/types/book";

export const libraryName = \`${esc(libraryName)}\`;

export const books: Book[] = ${JSON.stringify(
  enriched.map(({ seedDir, contentDir, knowledgebaseDir, outlinesDir, bookDir, imagesDir, coversDir, ...rest }) => rest),
  null,
  2
)} as Book[];

export function getBookBySlug(slug: string): Book | undefined {
  return books.find((b) => b.slug === slug);
}

export function getDefaultBook(): Book {
  return books[0];
}
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "books-registry.ts"), ts, "utf8");
console.log(`Synced books registry → src/data/books-registry.ts (${enriched.length} books)`);
