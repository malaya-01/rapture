#!/usr/bin/env node
/**
 * Generates src/data/books/<slug>/chapter-manifest.ts from seed JSON
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { booksToProcess, resolveBookPaths } from "./book-config.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..", "..");

function generateManifestTs(book, paths) {
  const manifestPath = paths.manifestOut;
  const arcsPath = join(paths.seedDir, "arcs.json");
  if (!existsSync(manifestPath) || !existsSync(arcsPath)) {
    console.warn(`Skip manifest TS for ${book.slug}: missing files`);
    return;
  }

  const chapterManifestSeed = JSON.parse(readFileSync(manifestPath, "utf8"));
  const arcsSeed = JSON.parse(readFileSync(arcsPath, "utf8"));

  const manifestChapters = chapterManifestSeed.chapters.map((c) => ({
    id: c.id,
    number: c.number,
    title: c.title,
    volumeId: c.volumeId,
    volumeNumber: c.volumeNumber,
    volumeTitle: c.volumeTitle,
    status: c.status,
    pov: c.pov,
    synopsis: c.synopsis,
  }));

  const manifestVolumes = arcsSeed.volumes.map((v) => ({
    id: v.id,
    number: v.number,
    title: v.title,
    chapterStart: v.chapterStart,
    chapterEnd: v.chapterEnd,
    ageId: v.ageId ?? v.actId ?? "act-1",
    purpose: v.purpose,
  }));

  const ts = `/** AUTO-GENERATED by seed/scripts/sync-book-manifest.mjs */
export interface ManifestChapter {
  id: string;
  number: number;
  title: string;
  volumeId: string;
  volumeNumber: number;
  volumeTitle: string;
  status: string;
  pov?: string;
  synopsis?: string;
}

export interface ManifestVolume {
  id: string;
  number: number;
  title: string;
  chapterStart: number;
  chapterEnd: number;
  ageId: string;
  purpose: string;
}

export const manifestVolumes: ManifestVolume[] = ${JSON.stringify(manifestVolumes, null, 2)};

export const manifestChapters: ManifestChapter[] = ${JSON.stringify(manifestChapters, null, 2)};

export function getManifestChapter(id: string) {
  return manifestChapters.find((c) => c.id === id);
}

export function getChaptersByVolume(volumeId: string) {
  return manifestChapters.filter((c) => c.volumeId === volumeId);
}

export function isChapterReadable(id: string, compiledIds: Set<string>) {
  const entry = getManifestChapter(id);
  if (!entry) return false;
  return entry.status === "published" && compiledIds.has(id);
}
`;

  mkdirSync(dirname(paths.manifestTsOut), { recursive: true });
  writeFileSync(paths.manifestTsOut, ts, "utf8");

  if (book.slug === "rapture") {
    writeFileSync(join(root, "src", "data", "chapter-manifest.ts"), ts, "utf8");
  }

  console.log(`[${book.slug}] Synced chapter-manifest.ts`);
}

for (const book of booksToProcess(process.argv)) {
  generateManifestTs(book, resolveBookPaths(book));
}
