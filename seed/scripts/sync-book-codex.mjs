#!/usr/bin/env node
/**
 * Syncs per-book codex seed JSON → src/data/books/<slug>/*.ts
 * Rapture uses sync-app-data.mjs (mirrored here). Other books use this script.
 * Run: node seed/scripts/sync-book-codex.mjs [--book <slug>]
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "fs";
import { dirname, extname, join } from "path";
import { fileURLToPath } from "url";
import { booksToProcess, resolveBookPaths } from "./book-config.mjs";

const IMAGE_EXT = [".png", ".webp", ".jpg", ".jpeg", ".svg"];
const CATEGORIES = [
  "characters",
  "monsters",
  "artifacts",
  "equipment",
  "dungeons",
  "locations",
  "companions",
  "disciples",
  "magic",
  "factions",
  "timeline",
  "scenes",
];

function readJson(path) {
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, "utf8"));
}

function readJsonArray(path, key) {
  const data = readJson(path);
  if (!data) return [];
  if (Array.isArray(data)) return data;
  return data[key] ?? [];
}

function esc(s) {
  return String(s ?? "").replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

function writeBookTs(outDir, filename, content) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, filename), content, "utf8");
}

function mapRole(role) {
  const r = String(role ?? "ally");
  if (r.includes("protagonist")) return "protagonist";
  if (r.includes("antagonist")) return "antagonist";
  return "ally";
}

function factionLabel(id) {
  if (!id) return "Unknown";
  return id
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function syncEchoesCodex(book, paths) {
  const seed = paths.seedDir;
  const out = paths.codexDataDir;
  const charactersSeed = readJsonArray(join(seed, "characters.json"), "characters");
  const locationsSeed = readJsonArray(join(seed, "locations.json"), "locations");
  const relationshipsSeed = readJsonArray(join(seed, "relationships.json"), "relationships");
  const timelineSeed = readJsonArray(join(seed, "timeline.json"), "events");
  const skillsSeed = readJsonArray(join(seed, "skills.json"), "skills");
  const scenesSeed = readJson(join(join(seed, "chapter-scenes.json")))?.scenes ?? [];

  const characters = charactersSeed.map((c) => ({
    id: c.id,
    name: c.name,
    role: mapRole(c.role),
    description: c.description ?? "",
    traits: c.traits ?? [],
    faction: factionLabel(c.house ?? c.faction),
    firstAppearance: c.firstAppearance ?? "ch-0001",
    imageColor:
      c.designation === "alpha"
        ? "#8b6b2e"
        : c.designation === "omega"
          ? "#4a3f6b"
          : "#718096",
  }));

  writeBookTs(
    out,
    "characters.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
import type { Character } from "@/types";

export const characters: Character[] = ${JSON.stringify(characters, null, 2)} as Character[];
`
  );

  const locations = locationsSeed.map((l) => ({
    id: l.id,
    name: l.name,
    region: l.region ?? "",
    description: l.description ?? "",
    firstAppearance: l.firstAppearance,
    minChapter: l.minChapter ?? 1,
    color: "#4a3f6b",
    promptId: l.id,
  }));

  writeBookTs(
    out,
    "locations.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export const locations = ${JSON.stringify(locations, null, 2)};
`
  );

  writeBookTs(
    out,
    "relationships.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export const relationships = ${JSON.stringify(relationshipsSeed, null, 2)};

export function getRelationshipsForCharacter(id: string) {
  return relationships.filter((r) => r.from === id || r.to === id);
}
`
  );

  const timelineEvents = timelineSeed.map((e) => ({
    id: e.id,
    title: e.title,
    era: e.era ?? "",
    description: e.description ?? "",
    chapter: e.chapter,
    minChapter: e.minChapter ?? 1,
    color: "#4a3f6b",
    promptId: e.id,
  }));

  writeBookTs(
    out,
    "timeline.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export const timelineEvents = ${JSON.stringify(timelineEvents, null, 2)};
`
  );

  const magicSkills = skillsSeed.map((s) => ({
    id: s.id,
    name: s.name,
    type: s.type ?? "magic",
    description: s.description ?? "",
    rank: s.rank ?? "C",
    color: "#553c9a",
    promptId: s.id,
    firstAppearance: s.firstAppearance,
  }));

  writeBookTs(
    out,
    "magic-skills.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export const magicSkills = ${JSON.stringify(magicSkills, null, 2)};
export const manaLaws: string[] = [];
export const magicMaterials: { id: string; name: string; description: string }[] = [];
export const magicRecipes: { id: string; name: string; description: string }[] = [];
`
  );

  for (const file of ["monsters.ts", "artifacts.ts", "equipment.ts", "dungeons-data.ts", "companions.ts", "factions-data.ts", "disciples.ts"]) {
    const exportName = file.replace(".ts", "").replace("-data", "");
    writeBookTs(
      out,
      file,
      `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export const ${exportName === "dungeons" ? "dungeons" : exportName} = [] as const;
`
    );
  }

  // Image manifest
  const manifestEntries = [];
  for (const cat of CATEGORIES) {
    mkdirSync(join(paths.imagesDir, cat), { recursive: true });
  }

  function manifestRow(category, id, title) {
    const dir = join(paths.imagesDir, category);
    let filePath = null;
    for (const ext of IMAGE_EXT) {
      const p = join(dir, `${id}${ext}`);
      if (existsSync(p)) {
        filePath = p;
        break;
      }
    }
    const present = filePath !== null;
    const ext = present ? extname(filePath) : ".png";
    const rel = `assets/images/${book.slug}/${category}/${id}${ext}`;
    manifestEntries.push({
      id,
      category,
      bookSlug: book.slug,
      title,
      filename: `${id}${ext}`,
      relativePath: rel,
      publicPath: `/${rel}`,
      status: present ? "present" : "missing",
      ...(present ? { version: statSync(filePath).mtimeMs } : {}),
    });
  }

  for (const c of characters) manifestRow("characters", c.id, c.name);
  for (const l of locations) manifestRow("locations", l.id, l.name);
  for (const e of timelineEvents) manifestRow("timeline", e.id, e.title);
  for (const s of magicSkills) manifestRow("magic", s.id, s.name);
  for (const scene of scenesSeed) manifestRow("scenes", scene.id, scene.title ?? scene.id);

  const present = manifestEntries.filter((e) => e.status === "present").length;
  writeBookTs(
    out,
    "image-manifest.ts",
    `/** AUTO-GENERATED by seed/scripts/sync-book-codex.mjs */
export type ImageCategory = ${CATEGORIES.map((c) => JSON.stringify(c)).join(" | ")};
export type ImageStatus = "present" | "missing";

export interface ImageManifestEntry {
  id: string;
  category: ImageCategory;
  bookSlug: string;
  title: string;
  filename: string;
  relativePath: string;
  publicPath: string;
  status: ImageStatus;
  version?: number;
}

export const imageManifest = {
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  bookSlug: ${JSON.stringify(book.slug)},
  summary: { total: ${manifestEntries.length}, present: ${present}, missing: ${manifestEntries.length - present} },
  entries: ${JSON.stringify(manifestEntries, null, 2)} as ImageManifestEntry[],
};

export function getManifestByCategory(category: ImageCategory) {
  return imageManifest.entries.filter((e) => e.category === category);
}
`
  );

  console.log(
    `[${book.slug}] Codex synced → ${out} (${characters.length} characters, ${manifestEntries.length} images)`
  );
}

function mirrorRaptureCodex(paths) {
  const rootData = join(paths.root, "src", "data");
  const out = paths.codexDataDir;
  const files = [
    "characters.ts",
    "locations.ts",
    "monsters.ts",
    "artifacts.ts",
    "equipment.ts",
    "dungeons-data.ts",
    "magic-skills.ts",
    "companions.ts",
    "factions-data.ts",
    "disciples.ts",
    "relationships.ts",
    "timeline.ts",
    "image-manifest.ts",
    "image-prompts.ts",
  ];
  mkdirSync(out, { recursive: true });
  for (const f of files) {
    const src = join(rootData, f);
    if (existsSync(src)) {
      let content = readFileSync(src, "utf8");
      if (f === "image-manifest.ts") {
        if (!content.includes("bookSlug?: string")) {
          content = content.replace(
            "export interface ImageManifestEntry {",
            "export interface ImageManifestEntry {\n  bookSlug?: string;"
          );
        }
        if (!content.includes('bookSlug: "rapture"')) {
          content = content.replace(
            'export const imageManifest = {',
            'export const imageManifest = {\n  bookSlug: "rapture",'
          );
        }
      }
      writeFileSync(join(out, f), content, "utf8");
    }
  }
  console.log(`[rapture] Codex mirrored → ${out}`);
}

for (const book of booksToProcess(process.argv)) {
  const paths = resolveBookPaths(book);
  if (book.slug === "rapture") {
    mirrorRaptureCodex(paths);
  } else {
    syncEchoesCodex(book, paths);
  }
}
